BY_ID = {p.id: p for p in PROTOCOLS}


# ── state ─────────────────────────────────────────────────────────────────

def _answers(store):
    try:
        value = json.loads(store.get_meta(META, "{}") or "{}")
        return value if isinstance(value, dict) else {}
    except (TypeError, ValueError):
        return {}


def _open_findings(protocol, snapshots, acks, now):
    return [f for job in protocol.jobs
            for f in (snapshots.get(job) or {}).get("findings") or ()
            if isinstance(f, dict) and f.get("severity") not in (None, "ok")
            and protocol.fixes(job, f)
            and not acknowledge.is_acknowledged(acks, f, job, now)]


def _projected_score(protocols, snapshots, schedule, acks, now):
    """The score with every finding these protocols resolve taken away."""
    trimmed = {}
    for job, snap in snapshots.items():
        findings = (snap or {}).get("findings") or []
        kept = [f for f in findings
                if not (isinstance(f, dict) and any(p.fixes(job, f) for p in protocols))]
        trimmed[job] = {**snap, "findings": kept}
    return score.compute(trimmed, schedule, now, acks)["score"]


def evaluate(store, schedule, now=None):
    """Every protocol with its state, pending question and projected score."""
    now = int(time.time() if now is None else now)
    snapshots = store.get_snapshots()
    acks = acknowledge.load(store)
    answers = _answers(store)
    current = score.compute(snapshots, schedule, now, acks)["score"]

    states, out = {}, []
    for p in PROTOCOLS:
        open_findings = _open_findings(p, snapshots, acks, now)
        fresh = all(job in schedule and score.freshness(snapshots.get(job), schedule[job][0], now)
                    == "current" for job in p.jobs)
        pending = next((q for q in p.questions
                        if (answers.get(f"{p.id}/{q.id}") or {}).get("answer") != YES), None)
        declined = pending is not None and \
            (answers.get(f"{p.id}/{pending.id}") or {}).get("answer") == NO
        blockers = [r for r in p.requires if states.get(r) != DONE]
        if not open_findings:
            state = DONE if fresh else UNVERIFIED
        elif blockers:
            state = BLOCKED
        elif declined:
            state = WAITING
        else:
            state = READY
        states[p.id] = state
        out.append({
            "protocol": p, "state": state, "open": len(open_findings), "blockers": blockers,
            "blocker_titles": [BY_ID[b].title for b in blockers],
            "question": pending, "declined": declined,
            "score_now": current,
            "score_after": (_projected_score([p], snapshots, schedule, acks, now)
                            if open_findings else current),
        })
    return out


def projected_all(store, schedule, now=None):
    """(score now, score once every protocol is complete)."""
    now = int(time.time() if now is None else now)
    snapshots, acks = store.get_snapshots(), acknowledge.load(store)
    return (score.compute(snapshots, schedule, now, acks)["score"],
            _projected_score(PROTOCOLS, snapshots, schedule, acks, now))


def pick_next(items):
    """The one protocol JARVIS would raise from an evaluated list, or None."""
    for wanted in (READY, WAITING):
        for item in items:
            if item["state"] == wanted:
                return item
    return None


def next_briefing(store, schedule, now=None):
    """The one protocol JARVIS would raise with you now, or None."""
    return pick_next(evaluate(store, schedule, now))


def answer(store, protocol_id, choice, now=None):
    """Answer the pending readiness question of a protocol. -> (ok, message)."""
    p = BY_ID.get(protocol_id)
    if not p:
        return False, f"no protocol named {protocol_id}"
    choice = {"y": YES, "yes": YES, "n": NO, "no": NO}.get((choice or "").strip().lower())
    if not choice:
        return False, "answer yes or no"
    answers = _answers(store)
    pending = next((q for q in p.questions
                    if (answers.get(f"{p.id}/{q.id}") or {}).get("answer") != YES), None)
    if pending is None:
        return False, f"{p.title}: nothing to answer — the steps are ready"
    answers[f"{p.id}/{pending.id}"] = {"answer": choice,
                                       "at": int(time.time() if now is None else now)}
    store.set_meta(META, json.dumps(answers, sort_keys=True))
    if choice == NO:
        return True, pending.if_no
    following = next((q for q in p.questions
                      if (answers.get(f"{p.id}/{q.id}") or {}).get("answer") != YES), None)
    return True, (f"Noted. Next: {following.ask}" if following
                  else "Noted. That's everything — the steps are yours.")


# ── words ─────────────────────────────────────────────────────────────────

def email_lines(item, items=()):
    """The briefing as a mail reader needs it: every step, in one place.

    The CLI withholds steps until the readiness questions are answered, because
    there it can ask. Mail is one-way, so the question is stated first and the
    steps follow it — nobody should have to run a command to find out how to
    turn on encryption.
    """
    p = item["protocol"]
    lines = [f"{p.title} [{item['state']}]", p.brief]
    gain = item["score_after"] - item["score_now"]
    if item["open"] and gain > 0:
        lines.append(f"Expected effect: security score {item['score_now']}% → "
                     f"{item['score_after']}%.")
    if item["state"] == BLOCKED:
        lines.append("First: " + ", ".join(BY_ID[b].title for b in item["blockers"])
                     + ". Doing these out of order causes trouble.")
    if item["question"]:
        lines.append(f"Answer first: {item['question'].ask}")
        lines.append(f"  jarvis brief yes {p.id}   |   jarvis brief no {p.id}")
        if item["declined"]:
            lines.append(f"  {item['question'].if_no}")
    lines += [f"{n}. {step}" for n, step in enumerate(p.steps, 1)]
    if p.alternative:
        lines.append("Or, in an elevated terminal:")
        lines += [f"  {cmd}" for cmd in p.alternative]
    if p.caution:
        lines.append(f"Caution: {p.caution}")
    queued = [i["protocol"].title for i in items
              if i["state"] in (READY, BLOCKED, WAITING) and i is not item]
    if queued:
        lines.append("Queued after this: " + ", ".join(queued) + ".")
    return lines


def render(item, full=True):
    """Plain-text briefing lines for one evaluated protocol."""
    p, state = item["protocol"], item["state"]
    lines = [f"PROTOCOL · {p.title}  [{state}]", p.brief]
    gain = item["score_after"] - item["score_now"]
    if item["open"] and gain > 0:
        lines.append(f"Expected effect: security score {item['score_now']}% → "
                     f"{item['score_after']}%.")
    if state == BLOCKED:
        names = ", ".join(BY_ID[b].title for b in item["blockers"])
        lines.append(f"First: {names}. Doing these out of order causes trouble.")
        if not full:
            return lines
    if state == DONE:
        lines.append("Verified by a fresh collector run. Nicely done.")
        return lines
    if state == UNVERIFIED:
        lines.append("No longer reported, but the collectors that check it are not current, "
                     f"so I can't confirm it yet: jarvis brief check {p.id}")
        return lines
    question = item["question"]
    if question and item["declined"]:
        lines += ["Before we go on:", f"  {question.if_no}",
                  f"When that's sorted: jarvis brief yes {p.id}"]
        return lines
    if question:
        lines += [f"A question first: {question.ask}",
                  f"  jarvis brief yes {p.id}   |   jarvis brief no {p.id}"]
        return lines
    steps = p.steps if full else p.steps[:3]
    lines += [f"{n}. {step}" for n, step in enumerate(steps, 1)]
    if not full and len(p.steps) > 3:
        lines.append(f"…and {len(p.steps) - 3} more: jarvis brief show {p.id}")
    if full and p.alternative:
        lines += ["Or, in an elevated terminal:"] + [f"  {cmd}" for cmd in p.alternative]
    if full and p.caution:
        lines.append(f"Caution: {p.caution}")
    return lines
