"""Protocols: JARVIS walks you through securing the machine, one mission at a time.

A finding says what is wrong. A protocol says what to do about it, in what
order, and whether you are ready. Each one is a short briefing in JARVIS's
voice with:

  * readiness questions it asks before handing over the steps ("somewhere to
    keep the recovery key that isn't this laptop?"). A "no" returns what to
    sort out first, never the steps;
  * the exact steps, written by hand. Instructions that can lock you out of
    your own disk are never generated by a model;
  * prerequisites, so encryption is not offered before Secure Boot (changing
    Secure Boot afterwards would demand the recovery key at the next boot);
  * verification from the collectors themselves. A protocol is done when its
    findings are gone from a *fresh* run of the jobs that raised them — not
    when you say so, and not when a collector has simply stopped looking;
  * the score it should earn, computed by the real scoring code with those
    findings removed.
"""

import json
import time
from dataclasses import dataclass

from jarvis.response import acknowledge
from jarvis.response.reporting import score

META = "protocol_answers_v1"

READY, BLOCKED, WAITING, DONE, UNVERIFIED = "ready", "blocked", "waiting", "done", "unverified"
YES, NO = "yes", "no"


@dataclass(frozen=True)
class Question:
    id: str
    ask: str
    if_no: str        # what to do before answering yes


@dataclass(frozen=True)
class Protocol:
    id: str
    title: str
    brief: str
    jobs: tuple                     # collectors whose fresh runs verify it
    resolves: tuple                 # (job, exact title | title prefix ending in "…")
    steps: tuple
    requires: tuple = ()
    questions: tuple = ()
    alternative: tuple = ()         # the same result by command, for the terminal-inclined
    caution: str = ""

    def fixes(self, job, finding):
        title = (finding or {}).get("title") or ""
        for owner, pattern in self.resolves:
            if owner != job:
                continue
            if pattern.endswith("…") and title.startswith(pattern[:-1]):
                return True
            if title == pattern:
                return True
        return False


